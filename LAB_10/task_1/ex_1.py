
import math

# 1. min и maxx
numbers = [5, 10, 25]
print(f"min({numbers}) = {min(numbers)}")
print(f"max({numbers}) = {max(numbers)}")

# 2. abs — модуль числа
negative = -7.25
print(f"abs({negative}) = {abs(negative)}")

# 3. math.sqrt — квадратный корень
num = 64
print(f"math.sqrt({num}) = {math.sqrt(num)}")

# 4. math.ceil и math.floor — округление
value = 1.4
print(f"math.ceil({value}) = {math.ceil(value)}")
print(f"math.floor({value}) = {math.floor(value)}")

# 5. math.pi — константа π
print(f"math.pi = {math.pi}")